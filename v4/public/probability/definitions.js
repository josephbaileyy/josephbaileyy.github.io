export function definitionMatcher(entry, entries) {
 const current=entries.findIndex(e=>e.n===entry);
 const aliases=definitions.filter(d=>entries.findIndex(e=>e.n===d.entry)<current)
  .flatMap(d=>d.aliases.map(alias=>({alias,...d}))).sort((a,b)=>b.alias.length-a.alias.length);
 const escaped=aliases.map(d=>d.alias.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'));
 return {pattern:new RegExp(`(?<![\\p{L}\\p{N}_-])(?!density of (?:the )?rational)(?:${escaped.join('|')})(?![\\p{L}\\p{N}_-])`,'giu'),
  lookup:new Map(aliases.map(d=>[d.alias.toLowerCase(),d]))};
}

// Math can separate the verb from “almost surely” in a single text node.
export function contextualDefinition(definition, before, entry, entries, after='') {
 // Prefer no link to a different mathematical concept. Bare “Borel” is
 // deliberately absent from aliases; explicit set/function phrases are safe.
 if(definition?.entry==='1.1.34' && /^\s+and separability\b/i.test(after))return null;
 if(definition?.entry==='1.2.48' && /\bkernel\s*$/i.test(before))return null;
 if(definition?.entry==='1.2.40' && ['1.3.7','1.3.56'].includes(entry))return null;
 if(definition?.entry==='1.1.44' && entry==='1.2.7')return null;
 if(definition?.entry==='1.2.34' && /zero[–-]one\s*$/i.test(before))return null;
 const math=before.match(/\$([^$]*)\$\s*$/)?.[1];
 const converging=math!==undefined ? /\\(?:to|longrightarrow|xrightarrow)(?![a-zA-Z])/.test(math)
  : /\bconverg(?:e(?:s|d)?|ing|ence)\b[^.!?;$]{0,100}$/i.test(before);
 if(definition?.entry==='1.2.8' && converging
  && entries.findIndex(e=>e.n==='1.2.25')<entries.findIndex(e=>e.n===entry))
  return definitions.find(d=>d.entry==='1.2.25');
 return definition;
}

export function linkDefinitions(root, entries) {
 for(const article of root.querySelectorAll('.entry')){
  const {pattern,lookup}=definitionMatcher(article.dataset.entry,entries);
  if(!lookup.size)continue;
  const walker=document.createTreeWalker(article,NodeFilter.SHOW_TEXT,{acceptNode(node){
   return node.parentElement.closest('a,button,textarea,label,summary,h3,.entry-meta,.prereqs,.visual-body,.label,script,style')
    ?NodeFilter.FILTER_REJECT:NodeFilter.FILTER_ACCEPT;
  }});
  const nodes=[];while(walker.nextNode())nodes.push(walker.currentNode);
  for(const node of nodes){
   // Protect TeX before KaTeX rendering; never put a link inside an expression.
   const fragment=document.createDocumentFragment();let count=0,partOffset=0;
   for(const part of node.textContent.split(/(\$\$[\s\S]*?\$\$|\$[^$]*?\$)/g)){
    if(part.startsWith('$')){fragment.append(part);partOffset+=part.length;continue}
    let offset=0;pattern.lastIndex=0;
    for(const match of part.matchAll(pattern)){
     const definition=contextualDefinition(lookup.get(match[0].toLowerCase()),node.textContent.slice(0,partOffset+match.index),article.dataset.entry,entries,node.textContent.slice(partOffset+match.index+match[0].length));
     if(!definition)continue;
     fragment.append(part.slice(offset,match.index));
     const link=document.createElement('a');link.className='definition-link';link.href='#entry-'+definition.entry.replaceAll('.','-');link.textContent=match[0];
     link.title=`${definition.label} · ${definition.entry} · statement and visualization`;
     fragment.append(link);offset=match.index+match[0].length;count++;
    }
    fragment.append(part.slice(offset));partOffset+=part.length;
   }
   if(count)node.replaceWith(fragment);
  }
 }
}
